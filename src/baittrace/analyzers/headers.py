"""Header hygiene.

Individually these are weak signals, and they are weighted accordingly. Their
value is corroborative: forged mail is assembled by a script rather than by a
mail client, and scripts leave a different fingerprint in the envelope than
Outlook or Postfix do.

Every check here is internal to the message. Nothing is compared against the
current clock, because a verdict that changes depending on when it was run is
not reproducible, and reproducibility is what lets a score from six months ago
still be explained.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from datetime import timedelta
from typing import ClassVar

from ..assets import registrable_domain
from ..model import Message
from ..signal import Category, Evidence, RuleSpec, Severity, Signal
from .base import Analyzer, Context
from .common import bulk_note, looks_like_bulk

_MESSAGE_ID_DOMAIN = re.compile(r"@([^>\s]+)>?\s*$")

# Headers where a duplicate is meaningful. A second From is the dangerous one:
# it exploits disagreement between the header an MTA validated and the header a
# mail client chooses to display.
_SINGLETON_HEADERS = ("from", "subject", "date", "message-id", "reply-to", "sender")
_DUPLICATE_WEIGHTS = {"from": 20.0, "reply-to": 12.0, "message-id": 10.0}
_DEFAULT_DUPLICATE_WEIGHT = 8.0

# How far the Date header may drift from the delivery chain before it is a
# finding. Generous, because relay clocks genuinely disagree.
_MAX_DATE_DRIFT = timedelta(hours=24)


HDR001 = RuleSpec(
    id="HDR001",
    category=Category.HEADERS,
    title="Duplicate single-occurrence header",
    severity=Severity.HIGH,
    weight=20.0,
    summary=(
        "A header that RFC 5322 allows only once appears more than once, so "
        "different software along the path may act on different values."
    ),
    advice=(
        "Compare the duplicated values. The one your client shows may not be the "
        "one that was validated."
    ),
    refs=("RFC 5322 section 3.6",),
    false_positives=(
        "Badly written bulk mailers occasionally emit a duplicate Reply-To or "
        "Subject without malicious intent."
    ),
)

HDR002 = RuleSpec(
    id="HDR002",
    category=Category.HEADERS,
    title="Message-ID is missing",
    severity=Severity.LOW,
    weight=6.0,
    summary="The message carries no Message-ID, which every normal mail client sets.",
    advice="Weak on its own. Note it alongside the other findings.",
    refs=("RFC 5322 section 3.6.4",),
    false_positives=(
        "Some internal automation and monitoring systems omit Message-ID. This is "
        "why the rule is weighted low."
    ),
)

HDR003 = RuleSpec(
    id="HDR003",
    category=Category.HEADERS,
    title="Message-ID domain does not match the sender",
    severity=Severity.MEDIUM,
    weight=8.0,
    summary="The Message-ID was generated by a different organisation than the From domain.",
    advice="Corroborating evidence only. Read it together with the sender findings.",
    refs=("RFC 5322 section 3.6.4",),
    false_positives=(
        "Very common and often innocent: any organisation using an email service "
        "provider will have provider-generated Message-IDs. Weighted low deliberately."
    ),
)

HDR004 = RuleSpec(
    id="HDR004",
    category=Category.HEADERS,
    title="Date header is malformed or contradicts delivery",
    severity=Severity.MEDIUM,
    weight=8.0,
    summary=(
        "The Date header cannot be parsed, or disagrees with the timestamps in the "
        "Received chain by more than a day."
    ),
    advice="A forged Date is often used to bury a message in a mailbox or to fake urgency.",
    refs=("RFC 5322 section 3.3",),
    false_positives=(
        "Badly configured relay clocks drift. The 24-hour tolerance exists to absorb that."
    ),
)

HDR005 = RuleSpec(
    id="HDR005",
    category=Category.HEADERS,
    title="Return-Path does not match the sender",
    severity=Severity.MEDIUM,
    weight=10.0,
    summary=(
        "The envelope sender, where bounces go, is a different organisation than the "
        "From header a reader sees."
    ),
    advice="Check whether the envelope sender is an expected mail provider for this brand.",
    refs=("RFC 5321 section 4.4", "RFC 7489"),
    false_positives=(
        "Mailing lists, forwarders and email service providers legitimately rewrite "
        "the envelope sender."
    ),
)


class HeaderAnalyzer(Analyzer):
    id: ClassVar[str] = "headers"
    prefix: ClassVar[str] = "HDR"
    category: ClassVar[Category] = Category.HEADERS
    requires_network: ClassVar[bool] = False
    RULES: ClassVar[tuple[RuleSpec, ...]] = (HDR001, HDR002, HDR003, HDR004, HDR005)

    def run(self, msg: Message, ctx: Context) -> Sequence[Signal]:
        signals: list[Signal] = []
        signals.extend(self._duplicates(msg))
        signals.extend(self._message_id(msg))
        signals.extend(self._date(msg))
        signals.extend(self._return_path(msg))
        return signals

    # -- HDR001 ------------------------------------------------------------

    def _duplicates(self, msg: Message) -> list[Signal]:
        duplicated = [name for name in _SINGLETON_HEADERS if msg.headers.count(name) > 1]
        if not duplicated:
            return []

        weight = max(_DUPLICATE_WEIGHTS.get(name, _DEFAULT_DUPLICATE_WEIGHT) for name in duplicated)
        evidence = [
            Evidence(locator=f"header:{header.name}#{header.index}", excerpt=header.raw_value)
            for name in duplicated
            for header in msg.headers.all(name)
        ]
        names = ", ".join(sorted(duplicated))
        return [
            HDR001.fire(
                confidence=0.95,
                weight=weight,
                explanation=(
                    f"These headers appear more than once: {names}. RFC 5322 permits one "
                    f"occurrence each. When a message carries two, the header a gateway "
                    f"validates and the header your mail client displays can be different "
                    f"ones, which is exactly what the technique exploits."
                ),
                evidence=evidence,
            )
        ]

    # -- HDR002 and HDR003 -------------------------------------------------

    def _message_id(self, msg: Message) -> list[Signal]:
        header = msg.headers.first("message-id")
        if header is None or not header.value.strip():
            return [
                HDR002.fire(
                    confidence=0.9,
                    explanation=(
                        "No Message-ID header is present. Mail clients and mail servers both "
                        "set one as a matter of course, so its absence suggests the message "
                        "was assembled by a script."
                    ),
                    evidence=[],
                )
            ]

        sender = msg.identity.primary_from
        if sender is None:
            return []

        match = _MESSAGE_ID_DOMAIN.search(header.value.strip())
        if match is None:
            return []

        mid_domain = registrable_domain(match.group(1).strip("<>").lower())
        from_domain = sender.registrable_domain or sender.domain
        if not mid_domain or not from_domain or mid_domain == from_domain:
            return []

        return [
            HDR003.fire(
                confidence=0.6,
                weight=3.0 if looks_like_bulk(msg) else HDR003.weight,
                explanation=(
                    f"The Message-ID was generated at {mid_domain} while the message claims to "
                    f"be from {from_domain}. This is normal for mail sent through a service "
                    f"provider, so it only matters alongside the other findings here."
                    + bulk_note(msg)
                ),
                evidence=[
                    Evidence(locator="header:Message-ID", excerpt=header.value),
                    Evidence(locator="header:From", excerpt=sender.raw),
                ],
            )
        ]

    # -- HDR004 ------------------------------------------------------------

    def _date(self, msg: Message) -> list[Signal]:
        dates = msg.dates
        if dates.missing:
            return []

        if dates.malformed or dates.parsed is None:
            return [
                HDR004.fire(
                    confidence=0.9,
                    explanation=(
                        f"The Date header {dates.raw!r} is not a valid RFC 5322 date. A mail "
                        f"client would have produced a well-formed one."
                    ),
                    evidence=[Evidence(locator="header:Date", excerpt=dates.raw)],
                )
            ]

        stamps = [hop.timestamp for hop in msg.routing.hops if hop.timestamp is not None]
        stamps = [s for s in stamps if s.tzinfo is not None]
        if not stamps or dates.parsed.tzinfo is None:
            return []

        latest = max(stamps)
        drift = abs(latest - dates.parsed)
        if drift <= _MAX_DATE_DRIFT:
            return []

        return [
            HDR004.fire(
                confidence=0.8,
                explanation=(
                    f"The Date header says {dates.parsed.isoformat()} but the delivery chain "
                    f"timestamps the message at {latest.isoformat()}, a difference of "
                    f"{drift.days} day(s). The two should agree closely."
                ),
                evidence=[
                    Evidence(locator="header:Date", excerpt=dates.raw),
                    Evidence(locator="header:Received", excerpt=latest.isoformat()),
                ],
            )
        ]

    # -- HDR005 ------------------------------------------------------------

    def _return_path(self, msg: Message) -> list[Signal]:
        return_path = msg.identity.return_path
        sender = msg.identity.primary_from
        if return_path is None or sender is None:
            return []

        envelope = return_path.registrable_domain or return_path.domain
        header_domain = sender.registrable_domain or sender.domain
        if not envelope or not header_domain or envelope == header_domain:
            return []

        return [
            HDR005.fire(
                confidence=0.8,
                weight=4.0 if looks_like_bulk(msg) else HDR005.weight,
                explanation=(
                    f"Bounces for this message go to {envelope}, but the reader sees "
                    f"{header_domain} as the sender. Legitimate providers do this too, so "
                    f"weigh it together with the authentication and identity findings."
                    + bulk_note(msg)
                ),
                evidence=[
                    Evidence(locator="header:Return-Path", excerpt=return_path.raw),
                    Evidence(locator="header:From", excerpt=sender.raw),
                ],
            )
        ]
